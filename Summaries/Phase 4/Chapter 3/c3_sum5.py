# =====================================================================
# 🧠 AGENT EXECUTORS — THE DIGITAL CONDUIT FOR AI AGENTS
# =====================================================================
# Agent Executor   -> The actual Python loop runner (manager) that executes
#                     tools requested by an LLM and feeds results back.
# The Thinker (LLM)-> The AI model generating reasoning and choosing tools.
# The Hands (Tools)-> Standard Python functions wrapped with descriptive
#                     docstrings so the AI knows exactly when to call them.
# The Notepad (State)-> The ongoing conversation history and trajectory log
#                     (Thought -> Action -> Observation) kept in memory.

# =====================================================================
# 🏢 ENTERPRISE PRODUCTION GUARDRAILS & DESIGN PATTERNS
# =====================================================================
# 🛠️ Modern Architecture:
#   - Legacy `AgentExecutor` classes are replaced by LangGraph pipelines.
#   - `create_react_agent` is the standard tool-calling agent framework.
#
# 🛡️ Anti-Crash Protection:
#   - Every tool must use try-except blocks to catch raw code exceptions.
#   - Instead of crashing, tools return error strings so the AI can self-heal.
#
# 🗜️ Strict Schema Enforcement:
#   - Real agencies use Pydantic `BaseModel` mappings for tool inputs (`args_schema`).
#   - This blocks mutated or corrupted text payloads generated by the LLM.
#
# 💰 API Token Cost Minimization:
#   - Tools must be atomic, doing exactly one isolated task clearly.
#   - Write hyper-descriptive docstrings to prevent infinite logic loops.
#   - Force system constraints inside `state_modifier` to restrict hallucinations.
