# =====================================================================
# 🧠 RATE LIMITING & PAGINATION DEFINITIONS
# =====================================================================
# Rate Limiting -> Server-enforced speed limits restricting request volumes.
# Pagination    -> Breaking massive datasets into small chunks called pages.
# HTTP 429      -> The official server status code for "Too Many Requests".
# Retry-After   -> A critical response header specifying wait time in seconds.
#
# =====================================================================
# ⚙️ PAGINATION ARCHITECTURAL PATTERNS
# =====================================================================
# 📑 Offset-Based Pagination:
#   - Relies on numeric counters passed inside request parameter blocks.
#   - `limit`    -> Tells the server how many items to return per page.
#   - `offset`   -> Tells the server how many rows to skip before reading.
#   - Iterates by incrementing offset: `offset += limit` per loop cycle.
#   - Terminal Condition: Terminates when an empty data list `[]` returns.
#
# 🍞 Cursor-Based Pagination:
#   - Relies on a random security bookmark token generated by the server.
#   - Metadata fields (e.g. `next` or `cursor`) supply the next page URL.
#   - The Python script pulls the token link and overwrites the loop target.
#   - Terminal Condition: Terminates when the token key returns `None` or empty.
#
# =====================================================================
# 🚨 COMMON REJECTED TRAPS & FIXES
# =====================================================================
# ❌ Infinite API Loops  -> Caused by failing to increment offset values.
#   - Fix: Mandate a rigorous check on item collection lengths per loop.
# ❌ Blind Fixed Sleeps  -> Causes massive pipeline execution delays.
#   - Fix: Extract `Retry-After` headers dynamically from server targets.
# ❌ Missing Key Crashes -> Occurs when downstream items possess null values.
#   - Fix: Always extract fields via safe `.get("key", default)` actions.
#
# =====================================================================
# 🇦🇺 SENIOR PRODUCTION GUARDRAILS
# =====================================================================
# 1. Never hardcode access tokens; isolate keys inside local `.env` frameworks.
# 2. Transition away from `print()` statements; utilize persistent logging files.
# 3. Apply Exponential Backoff policies when handling recurring 429 delays.
# 4. Maximize the `limit` query parameters to reduce aggregate HTTP network trips.
