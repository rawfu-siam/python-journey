# =====================================================================
# 🧠 CORE DEFINITIONS
# =====================================================================
# Swagger UI  -> An automatic, interactive web manual for testing code.
# `/docs`     -> The local default endpoint URL where the UI is hosted.
# OpenAPI     -> The open-standard rulebook FastAPI uses to build the UI.

# =====================================================================
# 🎨 VISUAL ANCHORS & ELEMENT MAPPING
# =====================================================================
# 🟢 GET Verb -> Rendered in green; used to read or fetch data states.
# 🔵 POST Verb-> Rendered in blue; used to trigger heavy automation runs.
# Docstrings  -> Triple-quote text comments that become endpoint descriptions.
# Type Hints  -> Python type settings that build interactive text boxes.

# =====================================================================
# 🛡️ THE ENTERPRISE AGENCY GUARDRAILS
# =====================================================================
# Pydantic    -> Reads `Field()` metadata to create auto-validating forms.
# Multi-Tags  -> Folders used to group messy scrapers into clean packages.
# Production  -> Turning `docs_url=None` via `.env` keys to hide secret paths.
# Portfolio   -> Deploying live `/docs` links to recruiters to prove your skill.
