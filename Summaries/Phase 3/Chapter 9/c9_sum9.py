# =====================================================================
# 🧠 CORE DEFINITIONS: PROPOSALS VS. BRIEFS
# =====================================================================
# Client Proposal -> A value-focused sales pitch pitching a business fix.
# Project Brief   -> An internal tech blueprint guiding developer code.
# Scope Creep     -> The dangerous expansion of unpaid client feature requests.
#
# =====================================================================
# 💼 THE PROPOSAL ANATOMY (The Client-Facing Sales Pitch)
# =====================================================================
# 1. The Problem   -> Clearly outlines the client's financial/time pain points.
# 2. The Solution  -> High-level overview of the AI system (No technical jargon).
# 3. Business ROI  -> Proves value by translating code into time or money saved.
# 4. Investment    -> Strict fixed-price quote with explicit delivery dates.
#
# =====================================================================
# 📜 THE PROJECT BRIEF ANATOMY (The Developer Rulebook)
# =====================================================================
# 🎯 Objective     -> The singular operational goal of the target script.
# 🚧 In-Scope      -> Granular checklist of features that WILL be coded.
# 🚫 Out-of-Scope  -> Boundary lines explicitly stating what will NOT be built.
# 🛠️ Tech Stack     -> Declares languages, APIs (OpenAI/Twilio), and DB frameworks.
# ✅ Acceptance    -> Testable, measurable numeric parameters that prove completion.
#
# =====================================================================
# 🎬 THE AGENCY DEV METHODOLOGY (How the Pros Cheat Legally)
# =====================================================================
# 🤖 AI Scaffolding -> Pros use LLM custom prompts to generate briefs in seconds.
# 🧘 Lazy Virtue    -> Use standardized modular brief templates to save time.
# 🔮 Golden Spell   -> "If it is not written inside In-Scope, it doesn't exist."
# 🧪 Pytest Matrix  -> Turn Acceptance Criteria directly into automated test files.

