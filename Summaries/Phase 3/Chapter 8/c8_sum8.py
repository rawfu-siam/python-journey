# =====================================================================
# 🧠 CORE DEFINITIONS & FUNDAMENTALS
# =====================================================================
# Linux    -> The rock-solid, open-source OS running 90%+ of cloud servers.
# Shell    -> The text-based interpreter that listens to your typed words.
# CLI      -> Command Line Interface (No mouse, no icons, pure text power).
# Formula  -> Command (Verb) + Flags/Options (Adverb) + Argument (Noun).

# =====================================================================
# 📁 THE BIG 5 NAVIGATION SPELLS
# =====================================================================
# pwd      -> "Print Working Directory". Shows exactly where you stand.
# ls       -> "List". Shows all files/folders in your current room.
# cd       -> "Change Directory". Teleports you into a specified folder.
# mkdir    -> "Make Directory". Spawns a brand new, clean folder.
# cat      -> "Concatenate". Dumps file contents straight onto your screen.

# =====================================================================
# 🛠️ PRODUCTION LOGGING & DEBUGGING TOOLS [Chapter 8, Extra 2]
# =====================================================================
# tail -f  -> "Follow". Streams background logs in real-time as they occur.
# clear    -> Wipes the terminal screen clean to remove cognitive clutter.
# history  -> Opens a chronological time-machine list of past commands.

# =====================================================================
# ⚠️ AGENCY GUARDRAILS & LAWS [Extra 3, Chapter 0]
# =====================================================================
# Case-Sensitive -> "Projects" and "projects" are totally different rooms.
# No Spaces      -> Never run `mkdir my bot`. Use `mkdir my_bot` instead.
# Isolation      -> Always configure app packages inside a localized venv.
# Security       -> Keep .env keys out of public repositories entirely.
# Laziness Rule  -> Tab-complete long names. Up-Arrow to re-run last step.
