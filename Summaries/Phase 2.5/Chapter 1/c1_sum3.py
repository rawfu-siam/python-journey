# =====================================================================
# 🧠 CORE DEFINITIONS & VISUAL PIPELINE
# =====================================================================
# Issue Status Tags -> Colored labels or columns tracking a task's stage.
# Asynchronous Info -> Teammates instantly know what is happening without
#                       needing to hold a meeting across time zones.
#
# The Journey: [Backlog] ➔ [Todo] ➔ [In Progress] ➔ [Review] ➔ [Done]
#
# 📥 BACKLOG: Raw ideas and future features kept on ice for later.
# 📋 TODO: Approved tasks that are completely ready for a developer.
# ⚙️ IN PROGRESS: Actively being coded in VS Code right now by someone.
# 👀 REVIEW / QA: Code is written, but a peer/senior must check it for bugs.
# 🎉 DONE: Code passed all tests, is merged, and deployed live to users!
# =====================================================================
# 🏢 THE AI AUTOMATION AGENCY MINDSET 
# =====================================================================
# 🤝 Remote Etiquette: 
#   - If a feature is not marked "In Progress" on the board, it doesn't exist.
#   - Keep all update details inside the issue thread, not direct DMs.
#   - Never skip the "Review" stage; local success does not equal production ready.
#
# 🦥 Proactive Laziness:
#   - Senior automation devs automate status transitions using scripts or APIs.
#   - "Smart Commits" allow you to use git messages to close issues automatically.
#
# 🧙‍♂️ The Automation Magic Spell:
#   "If a machine can track the state, never let a human dictate."
# =====================================================================
# ⚠️ COMMON BEGINNER PITFALLS & SOLUTIONS
# =====================================================================
# 1. String Typo Trap: Lowercase 'todo' vs Capital 'Todo' breaks matching logic.
#    - Solution: Enforce guardrails via strict data validation or objects.
# 2. Ghost Coding: Writing code for features before an issue card is created.
#    - Solution: No card, no code. Pull to "In Progress" before touching keys.
# 3. Silent Blockages: Leaving a card "In Progress" for days while stuck.
#    - Solution: Flag blockages early and tag a Senior Dev directly on the card.
# =====================================================================
